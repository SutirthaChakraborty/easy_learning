/**
 * The game catalogue.
 *
 * Every entry is data: an engine name, a content configuration, the functional
 * domains it trains, the life skill it transfers to, and which difficulty
 * dimensions the adaptive engine may move. No entry contains game logic — that
 * is the point of the engine split, and it is what makes a catalogue this size
 * maintainable and what would let a therapist author a new activity without
 * touching code.
 *
 * `domains` is not decoration. It decides which capability estimates a round
 * feeds, what the therapist dashboard aggregates, and how the hub groups games.
 * If a game's domains are wrong, the analytics are wrong.
 */
