// ── adaptive dimension presets ───────────────────────────────────────────────
// One dimension at a time is what the staircase moves; the ORDER here is the
// rotation, so it also encodes what to make harder first.
const DIMS = {
  discriminate: ['targetSize', 'choices', 'distractors', 'eccentricity', 'window'],
  memory: ['memorySpan', 'showMs', 'choices', 'distractors'],
  sequence: ['memorySpan', 'targetSize', 'eccentricity'],
  motor: ['targetSize', 'eccentricity', 'window'],
  inhibit: ['noGoRate', 'window', 'targetSize'],
  flexible: ['noGoRate', 'window', 'targetSize', 'ruleSwitch'],
  trace: ['tolerance', 'steps', 'eccentricity'],
  posture: ['holdMs', 'choices'],
  instruct: ['steps', 'choices', 'targetSize'],
  cue: ['holdMs', 'eccentricity'],
  wait: ['window', 'targetSize', 'eccentricity'],
  bilateral: ['targetSize', 'eccentricity'],
  rhythm: ['pace', 'targetSize', 'eccentricity'],
  collect: ['memorySpan', 'choices', 'targetSize', 'distractors'],
}

/** Builds a catalogue entry, filling in everything derivable. */
function g(entry) {
  return {
    usesReach: true,
    lifeSkillLabel: entry.lifeSkill ? LIFE_SKILL_LABELS[entry.lifeSkill] : null,
    adaptive: { dimensions: DIMS[entry.dims] || DIMS.discriminate, start: entry.start || {} },
    // Resolved lazily so an unknown engine name fails loudly at play time with
    // the game id in hand, rather than silently at module load.
    create: (self) => ENGINES[entry.engine](self),
    ...entry,
  }
}

