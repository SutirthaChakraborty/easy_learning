export const GAME_BY_ID = Object.fromEntries(GAMES.map((x) => [x.id, x]))

export function gamesInGroup(groupId) {
  return GAMES.filter((x) => x.group === groupId)
}

export function featuredGames() {
  return GAMES.filter((x) => x.featured)
}

export function getGame(id) {
  return GAME_BY_ID[id] || null
}

/** Every game that trains a given functional domain. */
export function gamesForDomain(domain) {
  return GAMES.filter((x) => (x.domains || []).includes(domain))
}

/** Every game that transfers to a given life skill. */
export function gamesForLifeSkill(skill) {
  return GAMES.filter((x) => x.lifeSkill === skill)
}
